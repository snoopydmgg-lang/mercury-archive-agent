def main():
    init_db()
    conn = get_conn()

    count = 0
    for name_cn, tier, category, rounds, desc in AUGMENTS_DATA:
        # 生成英文 key（用中文名的 hash 做唯一标识）
        key = f"aug_{hash(name_cn) & 0xFFFFFFFF:08x}"
        conn.execute("""
            INSERT OR REPLACE INTO augments (name, name_cn, tier, category, round_available, description)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (key, name_cn, tier, category, rounds, desc))
        count += 1

    conn.commit()
    conn.close()
    print(f"Augments imported: {count}")

if __name__ == "__main__":
    main()
